const player = (playerId: string): PlayerAttribution => ({ kind: "identified", playerId });

const quarterback = player("home-7");
const runningBack = player("home-22");
const receiver81 = player("home-81");
const receiver85 = player("home-85");

const own = (yardLine: number): FieldPosition => ({ side: "own", yardLine });
const opponent = (yardLine: number): FieldPosition => ({ side: "opponent", yardLine });

const before = (down: Down, distance: number, ballPosition: FieldPosition): ObservedContext => ({
  possession: "home",
  down,
  distance,
  ballPosition,
});

const rush = (
  observedContext: ObservedContext,
  ballCarrier: PlayerAttribution,
  yards: number,
): PlayObservation => ({
  family: "rush",
  outcome: "rush",
  period: 1,
  observedContext,
  segments: [{ kind: "rush", ballCarrier, yards }],
});

const completePass = (
  observedContext: ObservedContext,
  receiver: PlayerAttribution,
  yards: number,
): PlayObservation => ({
  family: "pass",
  outcome: "complete",
  period: 1,
  observedContext,
  segments: [{ kind: "reception", passer: quarterback, receiver, yards }],
});

const incompletePass = (
  observedContext: ObservedContext,
  target: PlayerAttribution,
): PlayObservation => ({
  family: "pass",
  outcome: "incomplete",
  period: 1,
  observedContext,
  segments: [{ kind: "incompletion", passer: quarterback, target }],
});

const revision = (
  play: number,
  revisionNumber: number,
  observation: PlayObservation,
  captureCompleteness: CaptureCompleteness = "complete",
  reviewStatus: ReviewStatus = "confirmed",
): PlayRevision => ({
  playId: `ref-play-${play}`,
  gameId,
  orderKey: String(play * 100).padStart(4, "0"),
  revision: revisionNumber,
  payloadVersion: 1,
  captureCompleteness,
  reviewStatus,
  observation,
});

